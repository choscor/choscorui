#[test]
fn missing_docs_and_examples_fail() {
    let mut view = parse(VIEW_JSON);
    set_docs(&mut view, "Label", "");
    set_docs(
        &mut view,
        "padding",
        "Space around the view, without an example.",
    );
    let mut facade = parse(FACADE_JSON);
    set_docs(
        &mut facade,
        "run",
        "Runs the application.\n\n```text\nno rust here\n```",
    );
    let error = generate(&world_from(facade, view), TOPICS).expect_err("content rules fail");
    for expected in [
        "no doc summary: choscorui::prelude::Label",
        "no `# Examples` section with a Rust code block: choscorui::prelude::Label (view type)",
        "no `# Examples` section with a Rust code block: choscorui::prelude::ViewExt::padding (modifier)",
        "no `# Examples` section with a Rust code block: choscorui::prelude::App::run (entry point method)",
    ] {
        assert!(error.contains(expected), "missing {expected:?} in {error}");
    }
}

#[test]
fn a_format_version_mismatch_names_both_versions() {
    let text = FACADE_JSON.replacen(
        &format!("\"format_version\":{}", crate::model::FORMAT_VERSION),
        "\"format_version\":1",
        1,
    );
    assert_ne!(text, FACADE_JSON, "the fixture names its format version");
    let error = Krate::from_json(parse(&text))
        .err()
        .expect("version 1 fails");
    assert_eq!(
        error,
        ModelError::FormatVersion {
            expected: crate::model::FORMAT_VERSION,
            actual: Some(1)
        }
    );
    assert!(
        error
            .to_string()
            .contains("bump tools/api-docs/nightly.txt and FORMAT_VERSION")
    );
}

