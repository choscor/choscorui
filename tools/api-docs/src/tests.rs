//! Renderer tests on the checked-in rustdoc JSON fixture in
//! `tests/fixture/`. They run on the stable toolchain.

use std::collections::{BTreeMap, BTreeSet};

use crate::json::{self, Json};
use crate::model::{Krate, ModelError, World};
use crate::render;

const FACADE_JSON: &str = include_str!("../tests/fixture/choscorui.json");
const VIEW_JSON: &str = include_str!("../tests/fixture/choscorui_view.json");

const TOPICS: &str = "\
# Fixture topics.
app choscorui::prelude::App
controls choscorui::prelude::Button
controls choscorui::prelude::Label
modifiers choscorui::prelude::ViewExt
layout choscorui::prelude::ViewExt::padding
styling choscorui::prelude::ViewExt::background
custom choscorui::prelude::View
custom choscorui::custom::CustomControl
";

fn parse(text: &str) -> Json {
    json::parse(text).expect("the fixture is valid json")
}

fn world_from(facade: Json, view: Json) -> World {
    let crates = [facade, view]
        .into_iter()
        .map(|json| Krate::from_json(json).expect("fixture format"));
    World::new(crates.collect())
}

fn world() -> World {
    world_from(parse(FACADE_JSON), parse(VIEW_JSON))
}

fn generate(world: &World, topics: &str) -> Result<BTreeMap<String, String>, String> {
    crate::generate(world, topics).map_err(|failure| failure.message)
}

/// Replaces the doc comment of the item named `name` in a JSON document.
fn set_docs(json: &mut Json, name: &str, docs: &str) {
    let Json::Object(top) = json else {
        panic!("fixture top level")
    };
    let Some(Json::Object(index)) = top.get_mut("index") else {
        panic!("fixture index")
    };
    let mut found = false;
    for item in index.values_mut() {
        if item.get("name").as_str() == Some(name)
            && let Json::Object(fields) = item
        {
            fields.insert("docs".into(), Json::String(docs.into()));
            found = true;
        }
    }
    assert!(found, "no item named {name}");
}

#[test]
fn renders_the_author_surface() {
    let pages = generate(&world(), TOPICS).expect("the fixture renders");
    let names: Vec<&str> = pages.keys().map(String::as_str).collect();
    assert_eq!(
        names,
        [
            "README.md",
            "app.md",
            "controls.md",
            "custom.md",
            "modifiers.md"
        ]
    );
    let readme = &pages["README.md"];
    assert!(readme.starts_with("<!-- Generated by choscorui-api-docs. Do not edit."));
    assert!(readme.contains("Every example assumes `use choscorui::prelude::*;`."));
    assert!(readme.contains("- [`Button`](controls.md#button) struct: A push button."));
    assert!(
        readme.contains("- [`padding`](modifiers.md#padding) modifier: Space around the view.")
    );
    assert!(readme.contains("- [`CustomControl`](custom.md#customcontrol) trait:"));

    let controls = &pages["controls.md"];
    assert!(controls.contains("struct in `choscorui::prelude::Button`"));
    assert!(controls.contains("pub struct Button { /* private fields */ }"));
    assert!(controls.contains("pub fn new(label: &str) -> Self"));
    assert!(controls.contains(
        "Modifiers: every [`ViewExt`](modifiers.md#viewext) method applies to this view."
    ));
    assert!(controls.contains("A button with a label. See [`Label`](#label)."));
    // Hidden lines are gone and the fence says `rust`.
    assert!(controls.contains("```rust\nlet button = Button::new(\"Save\");\n```"));
    assert!(!controls.contains("# use"));
    // A link to an item that is not in scope is plain text.
    assert!(controls.contains("The label text, for a `crate::internals::Tree` node."));

    let modifiers = &pages["modifiers.md"];
    let layout = modifiers.find("## Layout modifiers").expect("layout group");
    let styling = modifiers
        .find("## Styling modifiers")
        .expect("styling group");
    assert!(layout < modifiers.find("### `padding`").expect("padding") && styling > layout);
    assert!(pages["custom.md"].contains("- [`Button`](controls.md#button)"));
}

#[test]
fn leaves_out_internals_and_root_re_exports() {
    let pages = generate(&world(), TOPICS).expect("the fixture renders");
    for (name, text) in &pages {
        for internal in ["`Tree`", "NodeId", "choscorui::core"] {
            assert!(!text.contains(internal), "{name} shows {internal}");
        }
    }
}

#[test]
fn output_is_deterministic_and_well_formed() {
    let first = generate(&world(), TOPICS).expect("the fixture renders");
    let second = generate(&world(), TOPICS).expect("the fixture renders");
    assert_eq!(first, second);
    for (name, text) in &first {
        assert!(
            text.ends_with('\n') && !text.ends_with("\n\n"),
            "{name} ends with one newline"
        );
        assert!(
            !text.contains('\r') && !text.contains('\u{1}'),
            "{name} has stray characters"
        );
        assert!(
            !text.contains("/Users/") && !text.contains("\"id\""),
            "{name} leaks build details"
        );
    }
}

/// Every relative link names a generated file and, with a `#`, one of
/// its heading anchors.
#[test]
fn links_are_valid() {
    let pages = generate(&world(), TOPICS).expect("the fixture renders");
    let anchors: BTreeMap<&str, BTreeSet<String>> = pages
        .iter()
        .map(|(name, text)| {
            let mut seen: BTreeMap<String, usize> = BTreeMap::new();
            let mut fence = false;
            let mut set = BTreeSet::new();
            for line in text.lines() {
                if line.starts_with("```") {
                    fence = !fence;
                    continue;
                }
                let hashes = line.chars().take_while(|c| *c == '#').count();
                if fence || hashes == 0 || !line[hashes..].starts_with(' ') {
                    continue;
                }
                let base = render::slug(line[hashes..].trim());
                let count = seen.entry(base.clone()).or_insert(0);
                set.insert(if *count == 0 {
                    base.clone()
                } else {
                    format!("{base}-{count}")
                });
                *count += 1;
            }
            (name.as_str(), set)
        })
        .collect();
    let mut checked = 0;
    for (name, text) in &pages {
        let mut fence = false;
        for line in text.lines() {
            if line.starts_with("```") {
                fence = !fence;
            }
            if fence {
                continue;
            }
            let mut rest = line;
            while let Some(start) = rest.find("](") {
                let after = &rest[start + 2..];
                let end = after.find(')').expect("closed link");
                let target = &after[..end];
                rest = &after[end..];
                if target.contains("://") {
                    continue;
                }
                let (file, anchor) = target.split_once('#').unwrap_or((target, ""));
                let file = if file.is_empty() { name.as_str() } else { file };
                let set = anchors
                    .get(file)
                    .unwrap_or_else(|| panic!("{name}: link to missing {file}"));
                assert!(
                    anchor.is_empty() || set.contains(anchor),
                    "{name}: no anchor {target}"
                );
                checked += 1;
            }
        }
    }
    assert!(checked > 10, "the fixture pages have links");
}

