//! The gallery's single source of truth: which pages exist, which
//! `choscorui-controls` export each page shows, and why the remaining
//! exports have no page. `cargo test -p choscorui-gallery` fails when a
//! public name of `choscorui-controls` is missing here.

use crate::page::{Category, PageInfo};

macro_rules! page {
    ($id:literal, $title:literal, $category:ident) => {
        PageInfo {
            id: $id,
            title: $title,
            category: Category::$category,
        }
    };
}

